import assert from 'node:assert/strict';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';

const root=process.argv[2];
if(!root)throw Error('search-contracts.mjs PUBLISHED_WWWROOT');
const {BrowserTextActions}=await import(pathToFileURL(resolve(root,'_content/Doroti.Host.Web/doroti.web.text-actions.js')));
const timers=new Map(),popups=[];
let next=0,gesture=false;
globalThis.setTimeout=callback=>{timers.set(++next,callback);return next};
globalThis.clearTimeout=id=>timers.delete(id);
globalThis.window={open(url){
  assert.equal(gesture,true,'new windows must open within the gesture');
  assert.equal(url,'about:blank');
  const popup={closed:false,opener:{},urls:[],close(){this.closed=true}};
  popup.location={replace:url=>popup.urls.push(url)};
  popups.push(popup);
  return popup;
}};
const actions=new BrowserTextActions();
gesture=true;
actions.reserveSearchWindow();
actions.reserveSearchWindow();
gesture=false;
assert.equal(popups.length,1,'duplicate activation must not create two tabs');
assert.equal(popups[0].opener,null);
const text='한글 & <Qwerty> ? #';
assert.equal(await actions.invoke('SearchWeb.invoke',text),'opened');
assert.equal(new URL(popups[0].urls[0]).searchParams.get('q'),text);
assert.equal(timers.size,0,'navigation consumes reservation and timer');
gesture=true;
actions.reserveSearchWindow();
gesture=false;
assert.equal(await actions.invoke('SearchWeb.invoke','  '),'empty');
assert.equal(popups[1].closed,true,'empty selection releases its unused tab');
gesture=true;
actions.reserveSearchWindow();
gesture=false;
for(const callback of [...timers.values()])callback();
assert.equal(popups[2].closed,true,'missing Worker reply cleans up the unused tab');
assert.equal(timers.size,0);
gesture=true;
actions.reserveSearchWindow();
gesture=false;
actions.dispose();
assert.equal(popups[3].closed,true,'host disposal closes its unused tab');
assert.equal(popups[0].closed,false,'host disposal preserves the navigated search tab');
assert.equal(timers.size,0);
actions.reserveSearchWindow();
assert.equal(await actions.invoke('SearchWeb.invoke',text),'cancelled');
assert.equal(popups.length,4,'disposed host cannot open tabs');
console.log('PASS: gesture reservation, delayed navigation, query encoding, duplicate activation and cleanup');
