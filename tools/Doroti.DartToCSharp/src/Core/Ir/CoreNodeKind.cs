internal static class CoreNodeKindCatalog
{
    public static CoreNodeKind Parse(string value) =>
        Enum.TryParse<CoreNodeKind>(value, ignoreCase: false, out var result)
            ? result
            : CoreNodeKind.Unregistered;
}
