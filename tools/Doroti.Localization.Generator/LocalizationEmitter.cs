using System.Globalization;
using System.Text;
using Doroti.Runtime;
using Microsoft.CodeAnalysis.CSharp;

namespace Doroti.Localization.Generator;

internal static class LocalizationEmitter
{
    internal static string Emit(string ns, string className, ArbBundle template, ArbBundle[] bundles)
    {
        var output = new StringBuilder();
        output.AppendLine("// <auto-generated/>");
        output.AppendLine("#nullable enable");
        output.AppendLine("using __DorotiLocale = global::Doroti.Ui.Locale;");
        output.AppendLine($"namespace {ns};");
        output.AppendLine($"public abstract class {className}");
        output.AppendLine("{");
        output.AppendLine("    public const string GeneratorVersion = \"0.4.1-beta\";");
        output.AppendLine($"    private {className}(__DorotiLocale locale)");
        output.AppendLine("    {");
        output.AppendLine("        Locale = locale;");
        output.AppendLine("        __DorotiTag = locale.toLanguageTag();");
        output.AppendLine("    }");
        output.AppendLine("    public __DorotiLocale Locale { get; }");
        output.AppendLine("    private string __DorotiTag { get; }");
        output.AppendLine("    public static global::System.Collections.Generic.IReadOnlyList<__DorotiLocale> SupportedLocales { get; } =");
        output.AppendLine("        global::System.Array.AsReadOnly(new __DorotiLocale[]");
        output.AppendLine("        {");
        foreach (var bundle in bundles) output.AppendLine("            " + LocaleExpression(bundle.Locale) + ",");
        output.AppendLine("        });");
        output.AppendLine($"    public static global::Doroti.Framework.Widgets.LocalizationsDelegate<{className}> Delegate {{ get; }} = new __DorotiDelegate();");
        output.AppendLine($"    public static {className} Of(global::Doroti.Framework.Widgets.BuildContext context) =>");
        output.AppendLine($"        global::Doroti.Framework.Widgets.Localizations.of<{className}>(context, typeof({className}))");
        output.AppendLine($"        ?? throw new global::System.InvalidOperationException(\"Install {className}.Delegate in the widget tree.\");");
        output.AppendLine("    public static bool IsSupported(__DorotiLocale locale) => __DorotiLookup(locale) >= 0;");
        output.AppendLine($"    public static {className} Get(__DorotiLocale locale) => __DorotiLookup(locale) switch");
        output.AppendLine("    {");
        for (var i = 0; i < bundles.Length; i++)
            output.AppendLine($"        {i} => __DorotiResources{i}.For(locale.normalized()),");
        output.AppendLine("        _ => throw new global::System.ArgumentException($\"No ARB resource for {locale.toLanguageTag()}.\", nameof(locale)),");
        output.AppendLine("    };");

        WriteLookup(output, bundles);
        output.AppendLine($"    private sealed class __DorotiDelegate : global::Doroti.Framework.Widgets.LocalizationsDelegate<{className}>");
        output.AppendLine("    {");
        output.AppendLine("        public override bool isSupported(__DorotiLocale locale) => IsSupported(locale);");
        output.AppendLine($"        public override global::Doroti.Runtime.Future<{className}> load(__DorotiLocale locale) =>");
        output.AppendLine($"            new global::Doroti.Framework.Foundation.SynchronousFuture<{className}>(Get(locale));");
        output.AppendLine($"        public override bool shouldReload(global::Doroti.Framework.Widgets.LocalizationsDelegate<{className}> old) => false;");
        output.AppendLine("    }");

        foreach (var (key, entry) in template.Messages)
            output.AppendLine("    public abstract string " + Signature(key, entry.Placeholders)
                + (entry.Placeholders.Length == 0 ? " { get; }" : ";"));
        for (var i = 0; i < bundles.Length; i++) WriteBundle(output, className, template, bundles[i], i);
        output.AppendLine("}");
        return output.ToString().ReplaceLineEndings("\n");
    }

    private static void WriteLookup(StringBuilder output, ArbBundle[] bundles)
    {
        output.AppendLine("    private static int __DorotiLookup(__DorotiLocale locale)");
        output.AppendLine("    {");
        output.AppendLine("        if (!global::Doroti.Runtime.LocaleTag.TryCreate(locale.languageCode, locale.scriptCode, locale.countryCode, out var tag)) return -1;");
        output.AppendLine("        return (tag.Language, tag.Script, tag.Region) switch");
        output.AppendLine("        {");
        var order = bundles.Select((bundle, index) => (bundle.Locale, Index: index))
            .OrderByDescending(value => value.Locale.Region is not null).ThenByDescending(value => value.Locale.Script is not null);
        foreach (var (locale, index) in order)
        {
            // A declared script can cover its regions. A region without a script is exact.
            // A declared language-only resource is the explicit parent of its regional/script tags.
            var script = locale.Script is null && locale.Region is null ? "_" : NullableLiteral(locale.Script);
            var region = locale.Region is null ? "_" : Literal(locale.Region);
            output.AppendLine($"            ({Literal(locale.Language)}, {script}, {region}) => {index},");
        }
        output.AppendLine("            _ => -1,");
        output.AppendLine("        };");
        output.AppendLine("    }");
    }

    private static void WriteBundle(StringBuilder output, string className, ArbBundle template, ArbBundle bundle, int index)
    {
        output.AppendLine($"    private sealed class __DorotiResources{index} : {className}");
        output.AppendLine("    {");
        output.AppendLine($"        internal static readonly {className} Instance = new __DorotiResources{index}();");
        output.AppendLine($"        private __DorotiResources{index}() : base({LocaleExpression(bundle.Locale)}) {{ }}");
        output.AppendLine($"        private __DorotiResources{index}(__DorotiLocale locale) : base(locale) {{ }}");
        output.AppendLine($"        internal static {className} For(__DorotiLocale locale) =>");
        output.AppendLine($"            locale == Instance.Locale ? Instance : new __DorotiResources{index}(locale);");
        if (bundle.Messages.Values.Any(entry => entry.Placeholders.Any(p => p.Format is not null)))
        {
            output.AppendLine("        private global::Doroti.Intl.IntlFormatter? __DorotiFormatter;");
            output.AppendLine("        private global::Doroti.Intl.IntlFormatter __DorotiFormat => __DorotiFormatter ??= new(__DorotiTag);");
        }
        foreach (var (key, entry) in template.Messages)
        {
            var parameters = entry.Placeholders.ToDictionary(p => p.Name, StringComparer.Ordinal);
            output.AppendLine("        public override string " + Signature(key, entry.Placeholders) + " => "
                + MessageExpression(bundle.Messages[key].Parts, parameters) + ";");
        }
        output.AppendLine("    }");
    }

    private static string Signature(string name, Placeholder[] parameters) => parameters.Length == 0 ? name :
        name + "(" + string.Join(", ", parameters.Select(parameter => CSharpType(parameter.Type) + " @" + parameter.Name)) + ")";

    private static string CSharpType(string type) => type is "DateTime" or "TimeOnly" ? "global::System." + type : type;

    private static string MessageExpression(IReadOnlyList<MessagePart> parts, Dictionary<string, Placeholder> parameters)
    {
        var expressions = parts.Select(part => part switch
        {
            TextPart text => Literal(text.Value),
            PlaceholderPart placeholder => FormatParameter(parameters[placeholder.Name]),
            ChoicePart choice => ChoiceExpression(choice, parameters),
            _ => throw new InvalidOperationException("Unknown message part."),
        }).ToArray();
        return expressions.Length switch
        {
            0 => "\"\"",
            1 => expressions[0],
            _ => "string.Concat(" + string.Join(", ", expressions) + ")",
        };
    }

    private static string ChoiceExpression(ChoicePart choice, Dictionary<string, Placeholder> parameters)
    {
        var argument = "@" + choice.Placeholder;
        string BranchExpression(ChoiceBranch branch) => MessageExpression(branch.Parts, parameters);
        var other = BranchExpression(choice.Branches.Single(branch => branch.Key == "other"));
        var named = choice.Branches.Where(branch => branch.Exact is null && branch.Key != "other").ToArray();
        if (!choice.IsPlural)
            return SwitchExpression(argument, named.Select(branch => (Literal(branch.Key), BranchExpression(branch))), other);

        var category = named.Length == 0 ? other : SwitchExpression(
            $"global::Doroti.Intl.CardinalPlural.Select(__DorotiTag, {argument})",
            named.Select(branch => ("global::Doroti.Intl.PluralCategory." + char.ToUpperInvariant(branch.Key[0]) + branch.Key[1..], BranchExpression(branch))),
            other);
        var exact = choice.Branches.Where(branch => branch.Exact is not null).ToArray();
        return exact.Length == 0 ? category : SwitchExpression("(decimal)" + argument,
            exact.Select(branch => (branch.Exact!.Value.ToString(CultureInfo.InvariantCulture) + "m", BranchExpression(branch))), category);
    }

    private static string SwitchExpression(string input, IEnumerable<(string Pattern, string Body)> cases, string fallback) =>
        "(" + input + " switch { " + string.Concat(cases.Select(c => c.Pattern + " => " + c.Body + ", ")) + "_ => " + fallback + " })";

    private static string FormatParameter(Placeholder p)
    {
        var arg = "@" + p.Name;
        var digits = p.Digits?.ToString(CultureInfo.InvariantCulture);
        if (p.Format is "Hm" or "jm")
        {
            var time = p.Type == "DateTime" ? $"global::System.TimeOnly.FromDateTime({arg})" : arg;
            return $"__DorotiFormat.FormatTime({time}, {(p.Format == "Hm" ? "true" : "false")})";
        }
        var date = p.Format switch
        {
            "yMd" => "Compact", "yMMMd" => "Short", "MMMEd" => "Medium", "yMMMMEEEEd" => "Full",
            "yMMMM" => "MonthYear", "MMMd" => "ShortMonthDay", "y" => "Year", _ => null,
        };
        if (date is not null) return $"__DorotiFormat.FormatDate({arg}, global::Doroti.Intl.WidgetDateFormat.{date})";
        return p.Format switch
        {
            "decimalPattern" => p.Type is "int" or "long" ? $"__DorotiFormat.FormatInteger({arg})" : $"__DorotiFormat.FormatNumber({arg}, 2)",
            "decimalPatternDigits" => $"__DorotiFormat.FormatNumber({arg}, {digits ?? "2"})",
            "currency" or "simpleCurrency" => $"__DorotiFormat.FormatCurrency({arg}, {digits ?? "null"})",
            "percentPattern" or "decimalPercentPattern" => $"__DorotiFormat.FormatPercent({arg}, {digits ?? (p.Format == "percentPattern" ? "0" : "2")})",
            _ => p.Type == "string" ? $"({arg} ?? \"\")" : $"{arg}.ToString(global::System.Globalization.CultureInfo.InvariantCulture)",
        };
    }

    private static string LocaleExpression(LocaleTag tag) =>
        $"new __DorotiLocale({Literal(tag.Language)}, {NullableLiteral(tag.Region)}, {NullableLiteral(tag.Script)})";
    private static string NullableLiteral(string? value) => value is null ? "null" : Literal(value);
    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);
}
