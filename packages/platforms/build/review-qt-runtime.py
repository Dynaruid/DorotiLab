"""Materialize an explicit redistribution recipe as an exact SDK inventory.

A recipe has doroti.qt-sdk/v1 identity, archives, sources, documents, review,
buildConfiguration and selections: [{pattern: qml/QtQuick/*, module: Quick}].
Glob selections are nonrecursive unless the reviewer explicitly writes **.
Selections must exclude SDK tools and unreviewed modules. Sources/documents
already exist under the SDK prefix; hashes are recorded from their exact bytes.
"""
import argparse
import json
from pathlib import Path

from qt_runtime import digest, sdk_inventory, write_json


def review(sdk, recipe):
    data = json.loads(recipe.read_text())
    entries = {}
    for selection in data.pop("selections"):
        pattern = selection["pattern"]
        if Path(pattern).is_absolute() or ".." in Path(pattern).parts:
            raise ValueError("Selection must stay inside the SDK prefix")
        paths = [path for path in sdk.glob(pattern) if path.is_file()]
        if not paths:
            raise ValueError("Runtime selection matched no files: " + pattern)
        for path in paths:
            name = str(path.relative_to(sdk))
            # Select the real versioned Qt shared object once; SONAME aliases
            # are generated by the collector after RPATH rebasing.
            if path.is_symlink():
                if not path.resolve().is_relative_to(sdk.resolve()):
                    raise ValueError("SDK runtime selection escapes its prefix")
                if name.startswith("lib/"):
                    continue
            entry = dict(path=name, module=selection["module"], license=selection.get("license", "LGPL-3.0-only"), sha256=digest(path))
            if name in entries and entries[name] != entry:
                raise ValueError("Conflicting runtime review: " + name)
            entries[name] = entry
    data["files"] = list(entries.values())
    for entry in data["documents"] + data["sources"]:
        entry["sha256"] = digest(sdk / entry["path"])
    # Validate before replacing the prior approved manifest.
    path = sdk / "doroti-sdk.json"
    previous = path.read_bytes() if path.exists() else None
    try:
        write_json(path, data)
        sdk_inventory(sdk, data["version"], data["frameworkVersion"], data["kind"])
    except BaseException:
        if previous is None:
            path.unlink(missing_ok=True)
        else:
            path.write_bytes(previous)
        raise
    return path


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sdk", type=Path, required=True)
    parser.add_argument("--recipe", type=Path, required=True)
    args = parser.parse_args()
    try:
        print(review(args.sdk.resolve(), args.recipe.resolve()))
    except (ValueError, OSError, KeyError) as error:
        raise SystemExit("Qt redistribution review: " + str(error))
